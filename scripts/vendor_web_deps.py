#!/usr/bin/env python3
"""Vendor the web fonts and three.js, so no page depends on a third-party host.

The site used to take its typefaces from Google Fonts and three.js from
jsDelivr. Both are now served from this repository: a visit makes no request to
either, the desktop works when they are unreachable or blocked, and what a page
loads cannot change underneath it.

This script is how those copies were made and how they are replaced. It
downloads the pinned packages from the npm registry (so it needs `npm` and a
network connection, unlike the other generators) and writes:

  vendor/fonts/<family>/      the .woff2 files and each family's licence
  assets/css/fonts.css        @font-face rules for IBM Plex Mono and Dosis,
                              the two faces every page uses
  vendor/three/               three's minified module build, plus the addons
                              the site imports and everything they import

Re-run it after changing a version below, adding a weight, or importing a
three addon that is not vendored yet — add the addon to THREE_ADDONS first:

    python3 scripts/vendor_web_deps.py

Everything it writes is generated; edit this file rather than the output. The
import maps that point at vendor/three/ are not generated — they are in
index.html, the three apps that draw in 3D, and scripts/build_plain_site.py —
but they name no version, so a bump here needs no change there.
"""
import pathlib
import re
import shutil
import subprocess
import tarfile
import tempfile

root = pathlib.Path(__file__).resolve().parent.parent

THREE_VERSION = '0.178.0'
FONTSOURCE_VERSION = '5.3.0'

# family name in CSS, fontsource package, weights, stylesheet it is written to.
# 700 in Plex Mono is for the PCB heater designer, the one page that asks for it.
FONTS = [
    ('IBM Plex Mono', 'ibm-plex-mono', (400, 500, 600, 700), 'fonts.css'),
    ('Dosis', 'dosis', (500, 600, 700), 'fonts.css'),
]
# Latin covers English; latin-ext is the accented letters beyond it, which the
# unicode-range in each rule keeps off the wire until a page actually has one.
SUBSETS = ('latin-ext', 'latin')

# What the site imports as three/addons/…; their own imports are followed.
THREE_ADDONS = [
    'controls/OrbitControls.js',
    'environments/RoomEnvironment.js',
    'loaders/STLLoader.js',
    'loaders/OBJLoader.js',
    'loaders/3MFLoader.js',
    'loaders/GLTFLoader.js',
    'loaders/DRACOLoader.js',
    'loaders/KTX2Loader.js',
    'libs/meshopt_decoder.module.js',
]
# Decoders the glTF loaders fetch by URL at runtime rather than import, so no
# amount of following imports finds them.
THREE_RUNTIME_FILES = [
    'libs/draco/gltf/draco_decoder.js',
    'libs/draco/gltf/draco_decoder.wasm',
    'libs/draco/gltf/draco_wasm_wrapper.js',
    'libs/basis/basis_transcoder.js',
    'libs/basis/basis_transcoder.wasm',
]

FONT_CSS_HEADER = '''/* GENERATED by scripts/vendor_web_deps.py — do not edit by hand.
 *
 * %s, served from vendor/fonts/ rather than Google Fonts.
 * A rule costs nothing until text is set in that face, weight and range, so
 * every weight the site uses anywhere can be declared here once.
 */
'''


def fetch(package, into):
    """Download one npm package and return the path of its unpacked contents."""
    subprocess.run(['npm', 'pack', '--silent', package], cwd=into, check=True,
                   stdout=subprocess.DEVNULL)
    archive = max(into.glob('*.tgz'), key=lambda path: path.stat().st_mtime)
    target = into / archive.stem
    with tarfile.open(archive) as tar:
        tar.extractall(target, filter='data')
    archive.unlink()
    return target / 'package'


def unicode_range(package, name, subset, weight):
    """The range fontsource publishes for a subset, read from its own CSS."""
    css = (package / ('%d.css' % weight)).read_text(encoding='utf-8')
    block = re.search(r'/\* %s-%s-%d-normal \*/\s*@font-face\s*\{(.*?)\}'
                      % (re.escape(name), re.escape(subset), weight), css, re.S)
    return re.search(r'unicode-range:\s*([^;]+);', block.group(1)).group(1).strip()


def vendor_fonts(work):
    sheets = {}
    for family, name, weights, sheet in FONTS:
        package = fetch('@fontsource/%s@%s' % (name, FONTSOURCE_VERSION), work)
        out = root / 'vendor' / 'fonts' / name
        shutil.rmtree(out, ignore_errors=True)
        out.mkdir(parents=True)
        shutil.copy(package / 'LICENSE', out / 'LICENSE')
        rules = sheets.setdefault(sheet, {'families': [], 'rules': []})
        rules['families'].append(family)
        for weight in weights:
            for subset in SUBSETS:
                filename = '%s-%s-%d-normal.woff2' % (name, subset, weight)
                shutil.copy(package / 'files' / filename, out / filename)
                rules['rules'].append(
                    "@font-face {\n"
                    "  font-family: '%s';\n"
                    "  font-style: normal;\n"
                    "  font-weight: %d;\n"
                    "  font-display: swap;\n"
                    "  src: url('../../vendor/fonts/%s/%s') format('woff2');\n"
                    "  unicode-range: %s;\n"
                    "}\n" % (family, weight, name, filename,
                             unicode_range(package, name, subset, weight)))
    for sheet, data in sheets.items():
        text = FONT_CSS_HEADER % ' and '.join(data['families']) + '\n' + '\n'.join(data['rules'])
        (root / 'assets' / 'css' / sheet).write_text(text, encoding='utf-8')
        print('wrote assets/css/%s (%d faces)' % (sheet, len(data['rules'])))


def relative_imports(source):
    """Every relative module a file imports, statically or with import()."""
    found = re.findall(r'''(?:from|import)\s*\(?\s*['"](\.{1,2}/[^'"]+)['"]''', source)
    return set(found)


def vendor_three(work):
    package = fetch('three@%s' % THREE_VERSION, work)
    out = root / 'vendor' / 'three'
    shutil.rmtree(out, ignore_errors=True)
    (out / 'build').mkdir(parents=True)
    shutil.copy(package / 'LICENSE', out / 'LICENSE')
    # three.module.min.js imports three.core.min.js from beside it
    for name in ('three.module.min.js', 'three.core.min.js'):
        shutil.copy(package / 'build' / name, out / 'build' / name)

    jsm = package / 'examples' / 'jsm'
    wanted, queue = set(), [jsm / addon for addon in THREE_ADDONS]
    while queue:
        path = queue.pop().resolve()
        if path in wanted:
            continue
        wanted.add(path)
        if path.suffix == '.js':
            for target in relative_imports(path.read_text(encoding='utf-8')):
                queue.append(path.parent / target)
    wanted.update((jsm / name).resolve() for name in THREE_RUNTIME_FILES)

    for path in sorted(wanted):
        relative = path.relative_to(jsm.resolve())
        target = out / 'examples' / 'jsm' / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy(path, target)
    (out / 'VERSION').write_text(THREE_VERSION + '\n', encoding='utf-8')
    print('wrote vendor/three/ (three %s, %d addon files)' % (THREE_VERSION, len(wanted)))


def main():
    with tempfile.TemporaryDirectory() as work:
        work = pathlib.Path(work)
        vendor_fonts(work)
        vendor_three(work)


if __name__ == '__main__':
    main()
